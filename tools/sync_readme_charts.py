#!/usr/bin/env python3
"""Sync and check the README benchmark SVGs against the repository's version.

`README.md` embeds `docs/images/hash-epyc-128mib.svg` and `b3sum/README.md`
embeds `docs/images/b3sum-epyc-1000-files.svg`. Both are generated by full
`bench-hashes` runs on the EPYC 9255 (`bench-hashes.chart.svg` and
`b3sum.chart.svg`).

Usage:
    python3 tools/sync_readme_charts.py [--bench ../bench-hashes] [--git-ref REF]
    python3 tools/sync_readme_charts.py --check [COMMIT]

In sync mode, copies the newest EPYC 9255 `bench-hashes.chart.svg` and
`b3sum.chart.svg` from `bench-hashes` (working tree by default, or a git ref
such as `origin/next` via `--git-ref`) into `docs/images/`, verifying both
SVGs are valid and match `Cargo.toml`'s `X.Y.Z` release version.

In `--check` mode (also called by `tools/release-check.py`), verifies both
tracked SVGs exist and match `Cargo.toml`'s `X.Y.Z` version so a release
cannot ship stale README graphs.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

CHARTS = (
    ("hash", "docs/images/hash-epyc-128mib.svg", "bench-hashes.chart.svg"),
    ("b3sum", "docs/images/b3sum-epyc-1000-files.svg", "b3sum.chart.svg"),
)

_PACKAGE_VERSION_RE = re.compile(r'^\s*version\s*=\s*"(\d+\.\d+\.\d+)(?:[+-][^"]*)?"\s*$')
_SECTION_RE = re.compile(r"^\s*\[([^\]]+)\]\s*$")
_MEASURED_RE = re.compile(r"measured\s+(\d{4}-\d{2}-\d{2}\s+\d{2}:\d{2}:\d{2}\s+UTC)")
_CHART_VERSION_RES = {
    "hash": re.compile(r"BLAKE3[- ]servil\s+(\d+\.\d+\.\d+)(?:[+\s<]|$)", re.IGNORECASE),
    "b3sum": re.compile(r"\bb3sum\s+(\d+\.\d+\.\d+)(?:[+\s<]|$)"),
}


def parse_cargo_base_version(cargo_toml: str) -> str:
    """Return the `X.Y.Z` base version from `[package]` in `Cargo.toml`."""
    in_package = False
    for line in cargo_toml.splitlines():
        m_sec = _SECTION_RE.match(line)
        if m_sec:
            in_package = m_sec.group(1).strip() == "package"
            continue
        if in_package:
            m_ver = _PACKAGE_VERSION_RE.match(line)
            if m_ver:
                return m_ver.group(1)
    raise ValueError("Cargo.toml has no [package] version = \"X.Y.Z...\"")


def parse_chart_version(svg_text: str, kind: str) -> str | None:
    """Return the embedded `X.Y.Z` version from a bench-hashes chart SVG, or None."""
    if "<svg" not in svg_text or "</svg>" not in svg_text:
        return None
    m = _CHART_VERSION_RES[kind].search(svg_text)
    return m.group(1) if m else None


def parse_measured_timestamp(svg_text: str) -> str:
    """Return the `YYYY-MM-DD HH:MM:SS UTC` timestamp from a chart SVG, or ''."""
    m = _MEASURED_RE.search(svg_text)
    return m.group(1) if m else ""


def check_chart_texts(
    cargo_toml: str | None,
    hash_svg: str | None,
    b3sum_svg: str | None,
) -> tuple[bool, str]:
    """Check both README chart SVGs against `Cargo.toml`'s `X.Y.Z` version."""
    if cargo_toml is None:
        return False, "Cargo.toml is missing"
    try:
        expected = parse_cargo_base_version(cargo_toml)
    except ValueError as e:
        return False, str(e)

    problems = []
    for (kind, rel_path, _), text in zip(CHARTS, (hash_svg, b3sum_svg)):
        if text is None:
            problems.append(f"{rel_path} is missing")
            continue
        got = parse_chart_version(text, kind)
        if got is None:
            problems.append(f"{rel_path} is not a valid bench-hashes {kind} SVG with a version footer")
        elif got != expected:
            problems.append(f"{rel_path} is {got}, expected {expected}")
    if problems:
        return (
            False,
            "; ".join(problems)
            + "; run `python3 tools/sync_readme_charts.py --bench ../bench-hashes`",
        )
    return True, f"both README benchmark SVGs match {expected}"


def _git_show(repo: Path, commit: str, rel_path: str) -> str | None:
    r = subprocess.run(
        ["git", "-C", str(repo), "show", f"{commit}:{rel_path}"],
        capture_output=True,
        text=True,
    )
    return r.stdout if r.returncode == 0 else None


def check_repo(repo: Path, commit: str | None = None) -> tuple[bool, str]:
    """Check `repo` (working tree if `commit` is None, else git `commit`)."""
    if commit is None:
        def read_file(rel: str) -> str | None:
            p = repo / rel
            return p.read_text(encoding="utf-8") if p.is_file() else None
    else:
        def read_file(rel: str) -> str | None:
            return _git_show(repo, commit, rel)

    return check_chart_texts(
        read_file("Cargo.toml"),
        read_file(CHARTS[0][1]),
        read_file(CHARTS[1][1]),
    )


def _load_from_bench_fs(bench: Path, machine_prefix: str) -> tuple[str, dict[str, str]]:
    results_dir = bench / "benchmark-results"
    if not results_dir.is_dir():
        raise SystemExit(f"sync_readme_charts: no benchmark-results/ in {bench}")
    candidates = []
    for entry in sorted(results_dir.iterdir()):
        if not entry.is_dir() or not entry.name.startswith(machine_prefix):
            continue
        hash_p = entry / CHARTS[0][2]
        b3sum_p = entry / CHARTS[1][2]
        if hash_p.is_file() and b3sum_p.is_file():
            hash_txt = hash_p.read_text(encoding="utf-8")
            b3sum_txt = b3sum_p.read_text(encoding="utf-8")
            ts = parse_measured_timestamp(hash_txt)
            candidates.append((ts, entry.name, {"hash": hash_txt, "b3sum": b3sum_txt}))
    if not candidates:
        raise SystemExit(
            f"sync_readme_charts: no directory matching {machine_prefix}* with both chart SVGs in {results_dir}"
        )
    candidates.sort(key=lambda item: (item[0], item[1]))
    _, name, texts = candidates[-1]
    return name, texts


def _load_from_bench_git(bench: Path, git_ref: str, machine_prefix: str) -> tuple[str, dict[str, str]]:
    r = subprocess.run(
        ["git", "-C", str(bench), "ls-tree", "--name-only", git_ref, "benchmark-results/"],
        capture_output=True,
        text=True,
    )
    if r.returncode != 0:
        raise SystemExit(f"sync_readme_charts: git ls-tree failed for {bench} ({git_ref}): {r.stderr.strip()}")
    candidates = []
    for line in r.stdout.splitlines():
        name = Path(line.strip()).name
        if not name.startswith(machine_prefix):
            continue
        hash_txt = _git_show(bench, git_ref, f"benchmark-results/{name}/{CHARTS[0][2]}")
        b3sum_txt = _git_show(bench, git_ref, f"benchmark-results/{name}/{CHARTS[1][2]}")
        if hash_txt is not None and b3sum_txt is not None:
            ts = parse_measured_timestamp(hash_txt)
            candidates.append((ts, name, {"hash": hash_txt, "b3sum": b3sum_txt}))
    if not candidates:
        raise SystemExit(
            f"sync_readme_charts: no directory matching {machine_prefix}* with both chart SVGs in {bench}@{git_ref}"
        )
    candidates.sort(key=lambda item: (item[0], item[1]))
    _, name, texts = candidates[-1]
    return name, texts


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=".tmp-chart-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp_name, path)
    except BaseException:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)
        raise


def sync_charts(
    repo: Path,
    bench: Path,
    machine_prefix: str = "AMDEPYC9255",
    git_ref: str | None = None,
    allow_mismatch: bool = False,
) -> tuple[str, str]:
    """Copy both SVGs from `bench` into `repo/docs/images/` after validation."""
    cargo_toml = (repo / "Cargo.toml").read_text(encoding="utf-8")
    source_name, texts = (
        _load_from_bench_git(bench, git_ref, machine_prefix)
        if git_ref
        else _load_from_bench_fs(bench, machine_prefix)
    )
    ok, detail = check_chart_texts(cargo_toml, texts["hash"], texts["b3sum"])
    if not ok and not allow_mismatch:
        raise SystemExit(f"sync_readme_charts: refusing to write charts from {source_name}: {detail}")
    for kind, rel_path, _ in CHARTS:
        _atomic_write(repo / rel_path, texts[kind])
    return source_name, detail


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Sync or check the README benchmark SVGs.")
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parent.parent, help="BLAKE3 repository root")
    parser.add_argument("--check", nargs="?", const="", metavar="COMMIT", help="verify both SVGs match Cargo.toml (working tree or COMMIT)")
    parser.add_argument("--bench", type=Path, default=None, help="bench-hashes checkout (default: <repo>/../bench-hashes)")
    parser.add_argument("--git-ref", default=None, help="read charts from a git ref in --bench instead of its working tree")
    parser.add_argument("--machine", default="AMDEPYC9255", help="machine directory prefix under benchmark-results/ (default: AMDEPYC9255)")
    parser.add_argument("--allow-mismatch", action="store_true", help="write charts even if their version differs from Cargo.toml")
    args = parser.parse_args(argv)

    repo = args.repo.resolve()
    if args.check is not None:
        commit = args.check or None
        ok, detail = check_repo(repo, commit=commit)
        print(f"{'PASS' if ok else 'FAIL'}  sync_readme_charts: {detail}")
        return 0 if ok else 1

    bench = (args.bench if args.bench is not None else repo.parent / "bench-hashes").resolve()
    source_name, detail = sync_charts(
        repo,
        bench,
        machine_prefix=args.machine,
        git_ref=args.git_ref,
        allow_mismatch=args.allow_mismatch,
    )
    print(f"sync_readme_charts: updated docs/images/*.svg from {source_name} ({detail})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
